use proc_macro::{Span, TokenStream};
use quote::quote;
use syn::{
    Attribute,
    Expr,
    Ident,
    Token,
    Type,
    Visibility,
    parse::{Parse, ParseStream},
    parse_macro_input,
};

struct CpuLocal {
    attributes: Vec<Attribute>,
    visibility: Visibility,
    name: Ident,
    ty: Type,
    init: Expr,
}

impl Parse for CpuLocal {
    fn parse(input: ParseStream<'_>) -> syn::Result<Self> {
        let attributes = input.call(Attribute::parse_outer)?;
        let visibility: Visibility = input.parse()?;
        input.parse::<Token![static]>()?;
        let name: Ident = input.parse()?;
        input.parse::<Token![:]>()?;
        let ty: Type = input.parse()?;
        input.parse::<Token![=]>()?;
        let init: Expr = input.parse()?;
        input.parse::<Token![;]>()?;
        Ok(CpuLocal {
            attributes,
            visibility,
            name,
            ty,
            init,
        })
    }
}

#[proc_macro_attribute]
pub fn core_local(_args: TokenStream, input: TokenStream) -> TokenStream {
    let CpuLocal {
        attributes,
        visibility,
        name,
        ty,
        init,
    } = parse_macro_input!(input as CpuLocal);

    let cfg_attrs = attributes.iter().filter(|attr| attr.path().is_ident("cfg"));

    let stored_static_name = Ident::new(&format!("__CORE_LOCAL_{name}"), Span::call_site().into());

    // the static gets converted to some struct with accessor methods for the raw value. At init, the actual data behind the static gets copied to each cpu local storage section per core.
    // The one global static which is used to access the data sill not be copied, it should calcualte the correct offset from my_cpu() of the underlying core local data anr return a ptr to it.
    // again the considerations in core_local/lib.rs apply here.
    //
    // core idea:
    //
    // we store the actual static payload in a private static in the cpu_local link_section. At core_local init this will be copied to each core_local storage section.
    // We also store a static CoreLocal<T> var with the original name, which is used to access the statics copied to the core_local sections.
    // For this the CoreLocal stored in the static needs to compute the offset of the static payload data relative to the link section start. This can be computed from the addr of the private static raw data.
    //
    // I.e. a
    // core_local! { pub static FOO: AtomicPtr<Bar> = AtomicPtr::new(ptr::null()); };
    // becomes
    //
    // #[unsafe(link_section = ".cpu_local")]
    // #[used]
    // static __CORE_LOCAL_FOO: core_local::__private::CoreLocalStorage<AtomicPtr<Bar>> =
    //  core_local::__private::CoreLocalStorage::new(AtomicPtr:new(ptr::null()));
    //
    // pub static FOO: core_local::CoreLocal<AtomicPtr<Bar>> = core_local::CoreLocal::new(&raw const __CORE_LOCAL_FOO);
    //
    // __CORE_LOCAL_FOO can then be accessed via
    // GsBase + addr_of(__CORE_LOCAL_FOO) -  __core_local_section_start

    quote! {
        #(#cfg_attrs)*
        #[unsafe(link_section = ".cpu_local")]
        #[used]
        #[doc(hidden)]
        static #stored_static_name: ::core_local::__private::CoreLocalStorage<#ty> = ::core_local::__private::CoreLocalStorage::new(#init);

        #(#attributes)*
        #visibility static #name: ::core_local::CoreLocal<#ty> =
            // SAFETY: this is generated by the core_local::core_local macro. The static template sits in .cpu_local.
            unsafe { ::core_local::CoreLocal::new(&raw const #stored_static_name)} ;
    }
    .into()
}
